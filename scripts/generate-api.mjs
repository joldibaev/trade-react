// Regenerates src/api/schema.d.ts from TradeNet's OpenAPI document.
// The API must be running; OPENAPI_URL points at another copy (e.g. a second API on port 5199).
import { writeFile } from "node:fs/promises"
import openapiTS, { astToString } from "openapi-typescript"
import { fileURLToPath } from "node:url"
import { format, resolveConfig } from "prettier"

const url = process.env.OPENAPI_URL ?? "http://localhost:5129/openapi/v1.json"
const target = new URL("../src/api/schema.d.ts", import.meta.url)

let ast
try {
  ast = await openapiTS(new URL(url), { enum: false, exportType: true })
} catch (error) {
  console.error(`Could not read ${url}.`)
  console.error(
    "Start TradeNet (Rider or `dotnet run --project TradeNet`) and run `npm run api` again."
  )
  console.error(error instanceof Error ? error.message : error)
  process.exit(1)
}

const header =
  "// Generated by `npm run api` from TradeNet's OpenAPI document. Do not edit by hand.\n\n"
const path = fileURLToPath(target)
const options = await resolveConfig(path)
const source = await format(header + astToString(ast), {
  ...options,
  filepath: path,
})
await writeFile(path, source)
console.log(`Wrote ${path}`)
